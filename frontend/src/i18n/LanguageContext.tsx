const normalizedTranslations = new Map(
  Object.entries(translations).map(([source, translated]) => [
    source.toLowerCase(),
    translated,
  ]),
);

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    return window.localStorage.getItem("agrofarm-language") === "hi" ? "hi" : "en";
  });

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        window.localStorage.setItem("agrofarm-language", nextLanguage);
        setLanguageState(nextLanguage);
      },
      t: (text) =>
        language === "hi"
          ? translations[text] ?? normalizedTranslations.get(text.toLowerCase()) ?? text
          : text,
    }),
    [language],
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}